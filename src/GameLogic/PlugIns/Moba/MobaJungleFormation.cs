namespace MUnique.OpenMU.GameLogic.PlugIns.Moba;

using MUnique.OpenMU.DataModel.Configuration;
using MUnique.OpenMU.Pathfinding;

/// <summary>
/// Places the monsters of a jungle spot side by side in rows: the small ones in front (towards the entrance the players come from),
/// the bigger ones behind them (2026-10-17, requested by the user).
/// </summary>
public static class MobaJungleFormation
{
    /// <summary>Tiles between two monsters of a row.</summary>
    public const double Spacing = 2.0;

    /// <summary>Tiles between two rows.</summary>
    public const double RowDepth = 2.5;

    /// <summary>Most monsters in one row; more go to an extra row of the same size.</summary>
    public const int MaxPerRow = 4;

    /// <summary>A door closer than this (tiles) to the spot decides where the spot looks at.</summary>
    public const double DoorLookRange = 22;

    /// <summary>Radius (tiles) around the spot in which a free cell is searched for a monster.</summary>
    private const int SearchRadius = 9;

    /// <summary>The jungle entrances of the map (<c>Data/World200/MobaJungleDoors.txt</c>, generated by <c>tools/design_walls.py</c>).</summary>
    private static readonly (int X, int Y)[] Doors =
    {
        (43, 86), (185, 87), (71, 96), (127, 101), (210, 107), (107, 108), (165, 117), (130, 120), (193, 120), (97, 121),
        (43, 135), (106, 135), (139, 134), (71, 138), (129, 147), (26, 148), (109, 154), (165, 159), (51, 168), (193, 169),
    };

    /// <summary>The position of one monster of a spot.</summary>
    /// <param name="X">The x coordinate.</param>
    /// <param name="Y">The y coordinate.</param>
    /// <param name="Row">The row (0 = front).</param>
    /// <param name="Direction">The direction the monster looks at.</param>
    public sealed record Slot(byte X, byte Y, int Row, Direction Direction);

    /// <summary>Gets the unit vector a spot at the given position looks at: the nearest entrance if it is near, else the middle of the map.</summary>
    /// <param name="x">The x coordinate of the spot.</param>
    /// <param name="y">The y coordinate of the spot.</param>
    /// <returns>The unit vector.</returns>
    public static (double X, double Y) FacingAt(double x, double y)
    {
        var best = Doors.OrderBy(d => ((d.X - x) * (d.X - x)) + ((d.Y - y) * (d.Y - y))).First();
        var distance = Math.Sqrt(((best.X - x) * (best.X - x)) + ((best.Y - y) * (best.Y - y)));
        var (tx, ty) = distance <= DoorLookRange ? (best.X, best.Y) : (118.0, 128.0);
        var dx = tx - x;
        var dy = ty - y;
        var length = Math.Sqrt((dx * dx) + (dy * dy));
        return length < 0.01 ? (0, 1) : (dx / length, dy / length);
    }

    /// <summary>Gets the nearest of the eight directions to a vector.</summary>
    /// <param name="dx">The x component.</param>
    /// <param name="dy">The y component.</param>
    /// <returns>The direction.</returns>
    public static Direction DirectionOf(double dx, double dy)
    {
        var octant = (int)Math.Round(Math.Atan2(dy, dx) / (Math.PI / 4));
        var index = ((octant % 8) + 8) % 8;
        return index switch
        {
            0 => Direction.East,
            1 => Direction.SouthEast,
            2 => Direction.South,
            3 => Direction.SouthWest,
            4 => Direction.West,
            5 => Direction.NorthWest,
            6 => Direction.North,
            _ => Direction.NorthEast,
        };
    }

    /// <summary>Calculates the slots of the monsters of a spot.</summary>
    /// <param name="centerX">The x coordinate of the spot.</param>
    /// <param name="centerY">The y coordinate of the spot.</param>
    /// <param name="sizes">The size class of every monster (1 smallest). The result has the same order.</param>
    /// <returns>One slot per monster.</returns>
    public static IReadOnlyList<Slot> Layout(int centerX, int centerY, IReadOnlyList<int> sizes)
    {
        var (fx, fy) = FacingAt(centerX, centerY);
        var (px, py) = (-fy, fx);
        var direction = DirectionOf(fx, fy);

        // Rows: one per size class (front = smallest), split when a class has more than MaxPerRow monsters.
        var rows = new List<List<int>>();
        foreach (var group in Enumerable.Range(0, sizes.Count).GroupBy(i => sizes[i]).OrderBy(g => g.Key))
        {
            foreach (var chunk in group.Chunk(MaxPerRow))
            {
                rows.Add(chunk.ToList());
            }
        }

        var reachable = ReachableCells(centerX, centerY);
        var used = new HashSet<(int, int)>();
        var result = new Slot[sizes.Count];
        for (var r = 0; r < rows.Count; r++)
        {
            var depth = (((rows.Count - 1) / 2.0) - r) * RowDepth;
            var row = rows[r];
            for (var i = 0; i < row.Count; i++)
            {
                var lateral = (i - ((row.Count - 1) / 2.0)) * Spacing;
                var idealX = centerX + (fx * depth) + (px * lateral);
                var idealY = centerY + (fy * depth) + (py * lateral);
                var cell = NearestFree(reachable, used, idealX, idealY);
                used.Add(cell);
                result[row[i]] = new Slot((byte)cell.X, (byte)cell.Y, r, direction);
            }
        }

        return result;
    }

    private static (int X, int Y) NearestFree(List<(int X, int Y)> reachable, HashSet<(int, int)> used, double x, double y)
    {
        var best = (X: -1, Y: -1);
        var bestDistance = double.MaxValue;
        foreach (var cell in reachable)
        {
            if (used.Contains(cell))
            {
                continue;
            }

            var d = ((cell.X - x) * (cell.X - x)) + ((cell.Y - y) * (cell.Y - y));
            if (d < bestDistance)
            {
                bestDistance = d;
                best = cell;
            }
        }

        return best.X >= 0 ? best : ((int)Math.Round(x), (int)Math.Round(y));
    }

    /// <summary>The walkable cells connected to the spot within <see cref="SearchRadius"/> (a wall between two areas is never crossed).</summary>
    private static List<(int X, int Y)> ReachableCells(int centerX, int centerY)
    {
        var start = MobaLayout.NearestWalkable(centerX, centerY);
        var seen = new HashSet<(int, int)> { (start.X, start.Y) };
        var queue = new Queue<(int X, int Y)>();
        queue.Enqueue((start.X, start.Y));
        var list = new List<(int X, int Y)>();
        while (queue.Count > 0)
        {
            var (cx, cy) = queue.Dequeue();
            list.Add((cx, cy));
            for (var dy = -1; dy <= 1; dy++)
            {
                for (var dx = -1; dx <= 1; dx++)
                {
                    int nx = cx + dx, ny = cy + dy;
                    if ((dx == 0 && dy == 0)
                        || Math.Max(Math.Abs(nx - centerX), Math.Abs(ny - centerY)) > SearchRadius
                        || !MobaLayout.IsWalkable(nx, ny))
                    {
                        continue;
                    }

                    // No squeezing through a diagonal between two walls.
                    if (dx != 0 && dy != 0 && !MobaLayout.IsWalkable(cx + dx, cy) && !MobaLayout.IsWalkable(cx, cy + dy))
                    {
                        continue;
                    }

                    if (seen.Add((nx, ny)))
                    {
                        queue.Enqueue((nx, ny));
                    }
                }
            }
        }

        return list;
    }
}
